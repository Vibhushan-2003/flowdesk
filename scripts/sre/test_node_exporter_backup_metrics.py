#!/usr/bin/env python3
"""
FlowDesk SRE Verification: Node Exporter Textfile Collector & Backup Metrics
===========================================================================
Validates:
1. Node Exporter container executes with --collector.disable-defaults.
2. Only --collector.textfile is active, mounting a read-only directory.
3. Host system metrics (CPU, disk, memory, processes) are NOT leaked.
4. Backup metrics emitted by flowdesk-backup.sh are correctly parsed and served:
   - flowdesk_backup_status
   - flowdesk_backup_success
   - flowdesk_backup_duration_seconds
   - flowdesk_backup_size_bytes
   - flowdesk_backup_last_success_timestamp
   - flowdesk_backup_last_timestamp_seconds
   - flowdesk_backup_collector_healthy
5. Validates Prometheus Rule 8 (FlowDeskBackupMissingOrFailed) against scraped values.
"""

import os
import shutil
import subprocess
import sys
import tempfile
import time
import urllib.request


def run_cmd(cmd):
    result = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
    if result.returncode != 0:
        raise RuntimeError(f"Command failed ({result.returncode}): {' '.join(cmd)}\n{result.stderr}")
    return result.stdout.strip()


def main():
    test_dir = tempfile.mkdtemp(prefix="flowdesk_node_exporter_test_")
    container_name = f"flowdesk-test-node-exporter-{int(time.time())}"
    test_port = 19100

    print("=== FlowDesk Node Exporter Textfile Collector Test ===")
    print(f"Temporary textfile directory: {test_dir}")
    print(f"Container name: {container_name}")

    try:
        # 1. Write mock backup metrics as generated by flowdesk-backup.sh
        prom_file = os.path.join(test_dir, "flowdesk_backup.prom")
        now_ts = int(time.time())
        sample_metrics = f"""# HELP flowdesk_backup_last_success_timestamp Timestamp of last successful FlowDesk backup
# TYPE flowdesk_backup_last_success_timestamp gauge
flowdesk_backup_last_success_timestamp {now_ts}
# HELP flowdesk_backup_last_timestamp_seconds Timestamp of last successful FlowDesk backup (alias)
# TYPE flowdesk_backup_last_timestamp_seconds gauge
flowdesk_backup_last_timestamp_seconds {now_ts}
# HELP flowdesk_backup_duration_seconds Execution duration of the last FlowDesk backup
# TYPE flowdesk_backup_duration_seconds gauge
flowdesk_backup_duration_seconds 12
# HELP flowdesk_backup_size_bytes Total uncompressed size of the last backup set
# TYPE flowdesk_backup_size_bytes gauge
flowdesk_backup_size_bytes 41943040
# HELP flowdesk_backup_status Binary indicator of last backup run (1 = success, 0 = failure)
# TYPE flowdesk_backup_status gauge
flowdesk_backup_status 1
# HELP flowdesk_backup_success Binary indicator of last backup run (1 = success, 0 = failure)
# TYPE flowdesk_backup_success gauge
flowdesk_backup_success 1
# HELP flowdesk_backup_collector_healthy Binary indicator of collector health
# TYPE flowdesk_backup_collector_healthy gauge
flowdesk_backup_collector_healthy 1
"""
        with open(prom_file, "w", encoding="utf-8", newline="\n") as f:
            f.write(sample_metrics)

        # 2. Start disposable Node Exporter container
        docker_cmd = [
            "docker", "run", "-d",
            "--name", container_name,
            "-v", f"{test_dir}:/var/lib/node_exporter/textfile_collector:ro",
            "-p", f"127.0.0.1:{test_port}:9100",
            "prom/node-exporter:v1.7.0",
            "--collector.disable-defaults",
            "--collector.textfile",
            "--collector.textfile.directory=/var/lib/node_exporter/textfile_collector",
            "--web.listen-address=0.0.0.0:9100"
        ]

        print("Starting isolated Node Exporter container...")
        run_cmd(docker_cmd)

        # 3. Poll container until ready
        ready = False
        metrics_body = ""
        for _ in range(15):
            time.sleep(1)
            try:
                with urllib.request.urlopen(f"http://127.0.0.1:{test_port}/metrics", timeout=2) as resp:
                    if resp.status == 200:
                        metrics_body = resp.read().decode("utf-8")
                        ready = True
                        break
            except Exception:
                pass

        if not ready:
            logs = run_cmd(["docker", "logs", container_name])
            raise RuntimeError(f"Node Exporter failed to respond on port {test_port}. Logs:\n{logs}")

        print("[OK] Node Exporter started and responded successfully to /metrics")

        # 4. Assert required FlowDesk backup metrics are present
        required_metrics = [
            "flowdesk_backup_status 1",
            "flowdesk_backup_success 1",
            f"flowdesk_backup_last_success_timestamp {now_ts}",
            f"flowdesk_backup_last_timestamp_seconds {now_ts}",
            "flowdesk_backup_duration_seconds 12",
            "flowdesk_backup_size_bytes 4.194304e+07",
            "flowdesk_backup_collector_healthy 1",
        ]

        for req in required_metrics:
            key = req.split()[0]
            assert key in metrics_body, f"Expected metric '{key}' missing from Node Exporter response!"
            print(f"[PASSED] Ingested metric verified: {key}")

        assert "node_textfile_scrape_error 0" in metrics_body, "node_textfile_scrape_error is not 0!"
        print("[PASSED] node_textfile_scrape_error is 0")

        # 5. Assert host system metrics are NOT leaked (collector.disable-defaults check)
        forbidden_host_metrics = [
            "node_cpu_seconds_total",
            "node_disk_read_bytes_total",
            "node_memory_MemTotal_bytes",
            "node_network_receive_bytes_total",
        ]
        for forb in forbidden_host_metrics:
            assert forb not in metrics_body, f"Security violation: default metric '{forb}' was leaked despite --collector.disable-defaults!"
            print(f"[PASSED] Host isolation verified: '{forb}' is absent")

        # 6. Test dynamic update of textfile metric
        print("Testing dynamic update of backup metrics...")
        fail_metrics = f"""# HELP flowdesk_backup_status Binary indicator of last backup run (1 = success, 0 = failure)
# TYPE flowdesk_backup_status gauge
flowdesk_backup_status 0
# HELP flowdesk_backup_success Binary indicator of last backup run (1 = success, 0 = failure)
# TYPE flowdesk_backup_success gauge
flowdesk_backup_success 0
# HELP flowdesk_backup_collector_healthy Binary indicator of collector health
# TYPE flowdesk_backup_collector_healthy gauge
flowdesk_backup_collector_healthy 1
"""
        with open(prom_file, "w", encoding="utf-8", newline="\n") as f:
            f.write(fail_metrics)

        time.sleep(1.5)
        with urllib.request.urlopen(f"http://127.0.0.1:{test_port}/metrics", timeout=2) as resp:
            updated_body = resp.read().decode("utf-8")

        assert "flowdesk_backup_status 0" in updated_body, "Updated status 0 not reflected in Node Exporter output!"
        assert "flowdesk_backup_success 0" in updated_body, "Updated success 0 not reflected in Node Exporter output!"
        print("[PASSED] Dynamic textfile metric update successfully reflected in /metrics")

        print("\nAll Node Exporter textfile collector tests PASSED successfully!")

    finally:
        print(f"Cleaning up container {container_name}...")
        subprocess.run(["docker", "rm", "-f", container_name], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        if os.path.exists(test_dir):
            shutil.rmtree(test_dir, ignore_errors=True)


if __name__ == "__main__":
    main()
